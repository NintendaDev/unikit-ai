// Names of the engine-bridge layer. Not re-exported from `constants.ts` on purpose: that file sits at the
// Part 7i ceiling, and an `export *` back from here would be a cycle and a TDZ error (the same trap as SV-1c).

import path from 'path';
import { UNIKIT_DIR, systemDir } from './constants.js';

/** Subdirectory of the package `mcp/` catalog that holds the universal MCP servers (Context7, GitHub). */
export const UNIVERSAL_MCP_DIR_NAME = 'universal';

/** Release in which the engine-bridge migrations ship (the anchor of every step in `bridge-migrations/`). */
export const MIGRATION_SINCE_ENGINE_BRIDGES = '3.0.0';

/** Log tag of the bridge migration steps. */
export const BRIDGE_MIGRATE_LOG_TAG = 'bridges:migrate';

/** Folder of the delivered bridge layer under `.unikit/system/`: `BRIDGES.md` and one tree per bridge. */
export const ENGINE_BRIDGES_DIR_NAME = 'engine-bridges';

export const BRIDGES_MANIFEST_FILE = 'BRIDGES.md';

/** First line of BRIDGES.md: it is generated, and the next run rewrites it. */
export const BRIDGES_MANIFEST_HEADER = '<!-- Generated by unikit-ai init/update from .unikit.json and the package catalog. Do not edit: the next init/update rewrites it. -->';

/** Heading of the BRIDGES.md section for what every bridge of an engine needs (not one bridge's block). */
export const ENGINE_DOCS_HEADING = 'Engine-level documentation';

/** Where `/unikit-bridge-docs` copies documentation, under `.unikit/`: `references/bridges/<bridge id>/`. */
export const BRIDGE_REFERENCES_DIR = 'references/bridges';

/** The folder next to the bridges' own that holds the engine-level documentation. */
export const ENGINE_REFERENCES_DIR_NAME = '_engine';

/** The one file of a bridge's rules tree that the verify skill reads for the gate calibration. */
export const BRIDGE_VERIFICATION_FILE = 'verification.md';

/** Per-bridge findings logs live in `.unikit/bridge-notes/<bridge id>.md`. */
export const BRIDGE_NOTES_DIR_NAME = 'bridge-notes';

export const BRIDGE_NOTES_EXTENSION = '.md';

/** What marks a delivered rules file as provenance-stamped: only markdown is stamped, the rest is copied as it is. */
export const STAMPABLE_EXTENSION = '.md';

/** Key of the stamp line naming the bridge a delivered file came from; the notes header carries the same key. */
export const BRIDGE_STAMP_KEY = 'bridge:';
export const BRIDGE_STAMP_LINE_PREFIX = `${BRIDGE_STAMP_KEY} `;

/** `<projectDir>/.unikit/system/engine-bridges` — BRIDGES.md and the rules tree of every selected bridge. */
export function systemEngineBridgesDir(projectDir: string): string {
  return path.join(systemDir(projectDir), ENGINE_BRIDGES_DIR_NAME);
}

/** Parked notes live under `.unikit/bridge-notes/archive/`, one file per bridge (`<id>.md`, then `<id>.<n>.md`). */
export const BRIDGE_NOTES_ARCHIVE_DIR_NAME = 'archive';

/** `<projectDir>/.unikit/bridge-notes` — outside `system/` by construction: the logs are the project's own. */
export function bridgeNotesDir(projectDir: string): string {
  return path.join(projectDir, UNIKIT_DIR, BRIDGE_NOTES_DIR_NAME);
}

/** The active findings log of one bridge. */
export function bridgeNotesPath(projectDir: string, bridgeId: string): string {
  return path.join(bridgeNotesDir(projectDir), `${bridgeId}${BRIDGE_NOTES_EXTENSION}`);
}

export function bridgeNotesArchiveDir(projectDir: string): string {
  return path.join(bridgeNotesDir(projectDir), BRIDGE_NOTES_ARCHIVE_DIR_NAME);
}

/** The 2.x findings log and the prefix of its parked copies: literals of the layout the notes migration reads. */
export const LEGACY_NOTES_FILE = 'MCP-RECHECK-NOTES.md';
export const LEGACY_NOTES_ARCHIVE_PREFIX = 'MCP-RECHECK-NOTES.archive.';
